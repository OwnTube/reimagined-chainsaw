"""Check the owner's RCC script runtime requirements in the pinned Studio."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import tempfile
import time

from windows_probe import collect_logs, write_scene
from provided_scripts import source


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--studio',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    if os.name!='nt':parser.error('Native Windows is required')
    studio=args.studio.resolve(strict=True)
    specs=json.loads(Path(__file__).with_name('packages.json').read_text())
    digest=hashlib.sha256(studio.read_bytes()).hexdigest()
    if digest!=specs['studio']['executable_sha256']:raise ValueError('Studio identity mismatch')
    out=args.output.resolve();out.mkdir(parents=True,exist_ok=False)
    marker='RCC_SCRIPT_CAPABILITY_'+secrets.token_hex(12)
    report={'studio_sha256':digest,'probe_observed':False,'thumbnail_generator_available':False,
            'provided_scripts_executed':False,'engine_render_validated':False,
            'template_sha256':{kind:hashlib.sha256(source(kind).encode()).hexdigest() for kind in ('headshot','full_body')}}
    lua='''local marker=MARKER
print(marker .. "|STARTED")
local ok,result=pcall(function() return game:GetService("ThumbnailGenerator") end)
print(marker .. "|THUMBNAIL_GENERATOR|" .. tostring(ok) .. "|" .. tostring(result))
if ok and result then print(marker .. "|AVAILABLE") else print(marker .. "|UNAVAILABLE") end
'''.replace('MARKER',json.dumps(marker))
    # Capability probing does not execute the supplied site's asset/upload URLs.
    with tempfile.TemporaryDirectory(prefix='rcc-script-capability-') as temporary:
        runtime=Path(temporary)/'studio';shutil.copytree(studio.parent,runtime)
        owned=runtime/'BuiltInPlugins'/'Rcc2013Probe'
        if owned.exists():
            if 'Generated by RCC2013' not in (owned/'bootstrap.lua').read_text():
                raise RuntimeError('Unexpected renderer plugin content')
            shutil.rmtree(owned)
        place=out/'empty.rbxlx';write_scene(place)
        (out/'probe.lua').write_text(lua,encoding='utf-8')
        env=os.environ.copy()
        for key in ('QT_PLUGIN_PATH','QT_QPA_PLATFORM_PLUGIN_PATH'):env.pop(key,None)
        with (out/'process.log').open('wb') as stream:
            process=subprocess.Popen([str(runtime/studio.name),'-ide','-fileLocation',str(place),'-script',lua],cwd=runtime,env=env,stdout=stream,stderr=subprocess.STDOUT)
            try:
                deadline=time.monotonic()+35
                while time.monotonic()<deadline and process.poll() is None:
                    logs=collect_logs(out)+(out/'process.log').read_text(errors='replace')
                    if marker+'|AVAILABLE' in logs or marker+'|UNAVAILABLE' in logs:
                        report['probe_observed']=True
                        report['thumbnail_generator_available']=marker+'|AVAILABLE' in logs
                        report['engine_marker_lines']=list(dict.fromkeys(line for line in logs.splitlines() if marker in line))
                        break
                    time.sleep(1)
            finally:
                if process.poll() is None:
                    process.terminate()
                    try:process.wait(timeout=10)
                    except subprocess.TimeoutExpired:process.kill();process.wait(timeout=10)
    if not report['thumbnail_generator_available']:
        report['limitation']='The supplied RCC scripts require native ThumbnailGenerator; the Studio viewport renderer cannot execute their Click calls or reproduce their automatic full-body framing.'
    (out/'result.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
    # This is a capability observation, not a successful render test.
    return 0 if report['probe_observed'] else 1


if __name__=='__main__':raise SystemExit(main())
