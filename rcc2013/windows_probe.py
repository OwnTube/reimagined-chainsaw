def collect_logs(output):
    candidates = list((Path(os.environ['LOCALAPPDATA'])/'Roblox'/'logs').glob('*'))
    chunks = []
    for path in sorted((p for p in candidates if p.is_file()), key=lambda p:p.stat().st_mtime)[-12:]:
        if path.suffix.lower() not in ('.txt', '.log'):
            continue
        text = path.read_bytes()[-2*1024*1024:].decode('utf-8', errors='replace')
        chunks.append(text)
        lines = []
        for line in text.splitlines():
            if re.search(r'cookie|authorization|access_token|password|ticket', line, re.I):
                lines.append('[redacted authentication metadata]')
            else:
                lines.append(re.sub(r'(https?://[^\s?#]+)[?#][^\s]*', r'\1', line))
        (output/path.name).write_text('\n'.join(lines)+'\n', encoding='utf-8')
    return '\n'.join(chunks)


def windows_for_pid(pid):
    user32 = ctypes.windll.user32
    callback_type = ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)
    user32.GetWindowThreadProcessId.argtypes = [wintypes.HWND, ctypes.POINTER(wintypes.DWORD)]
    user32.GetWindowTextW.argtypes = [wintypes.HWND, wintypes.LPWSTR, ctypes.c_int]
    user32.GetClassNameW.argtypes = [wintypes.HWND, wintypes.LPWSTR, ctypes.c_int]
    user32.GetWindowRect.argtypes = [wintypes.HWND, ctypes.POINTER(wintypes.RECT)]
    user32.IsWindowVisible.argtypes = [wintypes.HWND]
    records = []
    child_handles = []
    top_level = True
    def inspect(handle, _):
        owner = wintypes.DWORD()
        user32.GetWindowThreadProcessId(handle, ctypes.byref(owner))
        if owner.value == pid:
            title, name, rect = ctypes.create_unicode_buffer(2048), ctypes.create_unicode_buffer(256), wintypes.RECT()
            user32.GetWindowTextW(handle, title, len(title))
            user32.GetClassNameW(handle, name, len(name))
            user32.GetWindowRect(handle, ctypes.byref(rect))
            records.append({'title':title.value,'class':name.value,'visible':bool(user32.IsWindowVisible(handle)),
                            'rect':[rect.left,rect.top,rect.right,rect.bottom],
                            'handle':int(handle),'top_level':top_level})
            child_handles.append(handle)
        return True
    callback = callback_type(inspect)
    user32.EnumWindows.argtypes = [callback_type, wintypes.LPARAM]
    user32.EnumChildWindows.argtypes = [wintypes.HWND, callback_type, wintypes.LPARAM]
    user32.EnumWindows(callback, 0)
    top_level = False
    for handle in list(child_handles):
        user32.EnumChildWindows(handle, callback, 0)
    return records


def resize_viewport(pid, size):
    """Resize only the owned Studio window; capture at native pixel resolution."""
    if size is None:
        return windows_for_pid(pid)
    user32 = ctypes.windll.user32
    records = windows_for_pid(pid)
    roots = [w for w in records if w['top_level'] and w['visible'] and
             w['title'].startswith('ROBLOX Studio')]
    if len(roots)!=1:
        raise RuntimeError('Cannot identify one owned Studio window for resizing')
    handle = roots[0]['handle']
    user32.ShowWindow.argtypes = [wintypes.HWND,ctypes.c_int]
    user32.SetForegroundWindow.argtypes = [wintypes.HWND]
    user32.SetWindowPos.argtypes = [wintypes.HWND,wintypes.HWND,ctypes.c_int,ctypes.c_int,
                                    ctypes.c_int,ctypes.c_int,wintypes.UINT]
    user32.ShowWindow(handle,9)  # SW_RESTORE, before changing a maximized window.
    user32.SetForegroundWindow(handle)
    time.sleep(0.5)
    for _ in range(4):
        records = windows_for_pid(pid)
        root = next(w for w in records if w['handle']==handle)
        views = [w for w in records if w['visible'] and w['title']=='QOgreWidget']
        if len(views)!=1:
            raise RuntimeError('Cannot identify one native render viewport for resizing')
        left,top,right,bottom = views[0]['rect']
        if right-left==size['width'] and bottom-top==size['height']:
            if left<0 or top<0 or right>user32.GetSystemMetrics(0) or bottom>user32.GetSystemMetrics(1):
                raise RuntimeError('Native viewport falls outside the visible desktop')
            return records
        x,y,r,b = root['rect']
        width = r-x + size['width']-(right-left)
        height = b-y + size['height']-(bottom-top)
        if width>user32.GetSystemMetrics(0) or height>user32.GetSystemMetrics(1):
            raise RuntimeError('Requested native image size does not fit this desktop with Studio window borders')
        if not user32.SetWindowPos(handle,None,0,0,width,height,0x0044):
            raise RuntimeError('Windows could not resize the owned Studio window')
        time.sleep(1)
    raise RuntimeError('Studio layout did not accept the requested native viewport size')


def render_pass(studio, output, place=None, camera=None, size=None, scene='blocks',
                matte=None, render_type='game_thumbnail'):
    if os.name != 'nt':
        raise RuntimeError('Native Windows with a desktop session is required')
    specs = json.loads(Path(__file__).with_name('packages.json').read_text())
    camera = camera or (AVATAR_CAMERA if scene=='avatar' else DEFAULT_CAMERA)
    studio = Path(studio).resolve(strict=True)
    if hashlib.sha256(studio.read_bytes()).hexdigest() != specs['studio']['executable_sha256']:
        raise ValueError('Executable identity mismatch')
    out = Path(output).resolve()
    out.mkdir(parents=True, exist_ok=False)
    marker = 'RCC2013_'+secrets.token_hex(12)
    default_blocks = place is None
    if place is None:
        place = out/'Rcc2013OwnedScene.rbxlx'
        write_scene(place)
    else:
        place = Path(place).resolve(strict=True)
    plugin = studio.parent/'BuiltInPlugins'/'Rcc2013Probe'/'bootstrap.lua'
    plugin.parent.mkdir(parents=True, exist_ok=True)
    if plugin.exists() and 'Generated by RCC2013' not in plugin.read_text(encoding='utf-8'):
        raise RuntimeError('The owned plugin path contains an unexpected existing file')
    plugin.write_text(plugin_source(marker, camera, default_blocks, scene, matte), encoding='utf-8')
    report = {'studio_sha256':specs['studio']['executable_sha256'],
              'scene_script_executed':False,'engine_render_validated':False,
              'screenshot_kind':'startup diagnostic, pending scene verification',
              'owned_addition':'BuiltInPlugins/Rcc2013Probe/bootstrap.lua',
              'launch_profile':'-ide -fileLocation owned.rbxlx', 'default_scene':default_blocks,
              'requested_size':size,'scene':scene if default_blocks else 'uploaded',
              'type':render_type,'matte_pass':matte,'camera':camera}
    if default_blocks and scene=='avatar':
        face = studio.parent/'content'/'textures'/'face.png'
        report['bundled_face_sha256'] = hashlib.sha256(face.read_bytes()).hexdigest()
    env = os.environ.copy()
    env.pop('QT_PLUGIN_PATH', None)
    env.pop('QT_QPA_PLATFORM_PLUGIN_PATH', None)
    with (out/'process.log').open('wb') as log:
        process = subprocess.Popen([str(studio), '-ide', '-fileLocation', str(place)],
            cwd=studio.parent, env=env, stdout=log, stderr=subprocess.STDOUT)
        try:
            start = time.monotonic()
            while process.poll() is None and time.monotonic()-start < 60:
                text = collect_logs(out)+(out/'process.log').read_text(errors='replace')
                if marker+'|SCENE_READY' in text:
                    report['scene_script_executed'] = True
                    report['engine_marker_lines'] = [line for line in text.splitlines() if marker in line]
                    report['avatar_structure_validated'] = marker+'|R6_READY|' in text
                    report['avatar_gui_free'] = marker+'|GUI_FREE|' in text
                    report['matte_ready'] = marker+'|MATTE_READY' in text
                    time.sleep(4)
                    break
                if marker+'|SCENE_ERROR|' in text:
                    report['scene_error'] = [line for line in text.splitlines() if marker+'|SCENE_ERROR|' in line]
                    break
                time.sleep(1)
            collect_logs(out)
            report['windows'] = windows_for_pid(process.pid)
            if report['scene_script_executed']:
                report['windows'] = resize_viewport(process.pid,size)
                if size is not None:
                    time.sleep(2)
            report['exit_code_before_cleanup'] = process.poll()
            from PIL import ImageGrab
            ImageGrab.grab().save(out/'runner-desktop.png')
            user32 = ctypes.windll.user32
            user32.GetForegroundWindow.restype = wintypes.HWND
            foreground_pid = wintypes.DWORD()
            user32.GetWindowThreadProcessId(user32.GetForegroundWindow(),ctypes.byref(foreground_pid))
            if foreground_pid.value != process.pid:
                raise RuntimeError('Studio must be foreground for native viewport capture')
            viewports = {tuple(w['rect']) for w in report['windows'] if w['visible'] and w['title']=='QOgreWidget'}
            if report['scene_script_executed'] and len(viewports)==1:
                bounds = next(iter(viewports))
                if bounds[0]<0 or bounds[1]<0 or bounds[2]-bounds[0]<64 or bounds[3]-bounds[1]<64:
                    raise RuntimeError('Unexpected native viewport bounds')
                image = ImageGrab.grab(bbox=bounds)
                image.save(out/'render.png')
                report['viewport_rect'] = list(bounds)
                report['image_size'] = list(image.size)
                report['native_size_matched'] = size is None or list(image.size)==[size['width'],size['height']]
                colors = {'red':0,'green':0,'blue':0,'yellow':0}
                for r,g,b in image.convert('RGB').getdata():
                    colors['red'] += r>80 and r>g*1.4 and r>b*1.4
                    colors['green'] += g>50 and g>r*1.2 and g>b*1.1
                    colors['blue'] += b>50 and b>r*1.2 and b>g*1.1
                    colors['yellow'] += r>80 and g>80 and b<min(r,g)*0.6
                report['dominant_color_pixels'] = colors
                required = (('yellow','blue') if render_type=='headshot' else ('yellow','green','blue')) if scene=='avatar' else ('red','green','blue')
                fixture_valid = all(colors[c]>100 for c in required)
                if default_blocks and scene=='avatar':
                    fixture_valid = fixture_valid and report.get('avatar_structure_validated',False) and report.get('avatar_gui_free',False)
                if matte is not None:
                    fixture_valid = fixture_valid and report.get('matte_ready',False)
                report['engine_render_validated'] = report['native_size_matched'] and (not default_blocks or fixture_valid)
                report['render_method'] = 'native QOgreWidget framebuffer screen capture'
                report['png_sha256'] = hashlib.sha256((out/'render.png').read_bytes()).hexdigest()
            report['captured_at_utc'] = datetime.now(timezone.utc).isoformat()
        finally:
            if process.poll() is None:
                process.terminate()
                try:
                    process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait(timeout=10)
            (out/'result.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    return report


def render_scene(studio, output, place=None, camera=None, size=None, scene='blocks',render_type=None):
    render_type = render_type or ('full_body' if scene=='avatar' else 'game_thumbnail')
    if render_type=='game_thumbnail':
        return render_pass(studio,output,place,camera,size,scene,render_type=render_type)
    if render_type not in ('headshot','full_body') or place is not None or scene!='avatar':
        raise ValueError('Player thumbnails require the owned avatar scene')
    from PIL import Image
    from matting import recover_alpha
    out=Path(output).resolve();out.mkdir(parents=True,exist_ok=False)
    camera=camera or (HEADSHOT_CAMERA if render_type=='headshot' else AVATAR_CAMERA)
    size=size or {'width':512,'height':512}
    report={'type':render_type,'scene':'avatar','engine_render_validated':False,'passes':[],
            'camera':camera,'camera_profile':'BubbaBlox v2 no-hat R6 equivalent' if render_type=='headshot' and camera==HEADSHOT_CAMERA else 'custom'}
    try:
        for matte in ('dark','light'):
            result=render_pass(studio,out/matte,None,camera,size,'avatar',matte,render_type)
            report['passes'].append(result)
            if not result.get('engine_render_validated'):
                raise RuntimeError('Native '+matte+' avatar pass did not validate')
        with Image.open(out/'dark'/'render.png') as dark, Image.open(out/'light'/'render.png') as light:
            image,stats=recover_alpha(dark,light)
        if stats['alpha_counts'].get('opaque',0)<100 or stats['alpha_counts'].get('transparent',0)<100:
            raise RuntimeError('Avatar alpha does not contain both the player and clear background')
        image.save(out/'render.png')
        report.update(stats)
        report.update({'engine_render_validated':True,'scene_script_executed':True,
                       'avatar_structure_validated':True,'avatar_gui_free':True,
                       'image_size':list(image.size),'image_mode':'RGBA','transparent':True,
                       'native_size_matched':True,
                       'render_method':'two native QOgreWidget captures with calibrated alpha recovery',
                       'png_sha256':hashlib.sha256((out/'render.png').read_bytes()).hexdigest()})
        return report
    except Exception as error:
        report['error']=str(error)
        raise
    finally:
        (out/'result.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--studio', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path('output'))
    args = parser.parse_args()
    report = render_scene(args.studio, args.output)
    print(json.dumps(report, indent=2))
    return 0 if report['engine_render_validated'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
