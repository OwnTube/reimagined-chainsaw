def write_scene(path):
    root = ET.Element('roblox', version='4')
    for value in ('null', 'nil'):
        ET.SubElement(root, 'External').text = value
    workspace = ET.SubElement(root, 'Item', {'class': 'Workspace', 'referent': 'RBX0'})
    props = ET.SubElement(workspace, 'Properties')
    ET.SubElement(props, 'string', name='Name').text = 'Workspace'
    ET.ElementTree(root).write(path, encoding='utf-8', xml_declaration=True)


DEFAULT_CAMERA = {'position': [19,15,23], 'target': [0,2,0], 'fov': 50}
AVATAR_CAMERA = {'position':[7,5,-10], 'target':[0,2.6,0], 'fov':35}


def plugin_source(marker, camera=None, default_blocks=True, scene='blocks', matte=None):
    camera = camera or (AVATAR_CAMERA if scene=='avatar' else DEFAULT_CAMERA)
    return '''
-- Generated by RCC2013 for one owned render job.
local marker = MARKER
print(marker .. "|PLUGIN_LOADED")
local ok, problem = pcall(function()
        local world = game:GetService("Workspace")
        if MAKE_BLOCKS then
        local model = Instance.new("Model")
        model.Name = "RCC2013_OwnedScene"
        model.Parent = world
        local function block(name, color, position, size)
            local part = Instance.new("Part")
            part.Name = name
            part.Anchored = true
            part.BrickColor = BrickColor.new(color)
            part.Size = size
            part.CFrame = CFrame.new(position)
            part.TopSurface = Enum.SurfaceType.Studs
            part.BottomSurface = Enum.SurfaceType.Smooth
            part.Parent = model
        end
        block("Floor", 194, Vector3.new(0,-0.5,0), Vector3.new(32,1,24))
        block("Red", 21, Vector3.new(-4,2,0), Vector3.new(3,4,3))
        block("Green", 37, Vector3.new(0,3,0), Vector3.new(4,6,4))
        block("Blue", 23, Vector3.new(4,2,0), Vector3.new(3,4,3))
        end
        AVATAR_SETUP
        local camera = world.CurrentCamera
        if not camera then
            camera = Instance.new("Camera")
            camera.Parent = world
            world.CurrentCamera = camera
        end
        camera.CameraType = Enum.CameraType.Scriptable
        camera.CoordinateFrame = CFrame.new(Vector3.new(EYE), Vector3.new(TARGET))
        camera.Focus = CFrame.new(TARGET)
        camera.FieldOfView = FOV
        print(marker .. "|CAMERA_READY|eye=" .. tostring(camera.CoordinateFrame.p) .. "|target=" .. tostring(camera.Focus.p) .. "|fov=" .. tostring(camera.FieldOfView))
        BACKDROP_SETUP
        print(marker .. "|SCENE_READY")
end)
if not ok then print(marker .. "|SCENE_ERROR|" .. tostring(problem)) end
'''.replace('MARKER', json.dumps(marker)).replace('MAKE_BLOCKS', 'true' if default_blocks and scene=='blocks' else 'false').replace(
    'AVATAR_SETUP',Path(__file__).with_name('avatar.lua').read_text() if default_blocks and scene=='avatar' else '').replace(
    'BACKDROP_SETUP',backdrop_source(matte) if matte is not None else '').replace(
    'EYE', ','.join(str(v) for v in camera['position'])).replace(
    'TARGET', ','.join(str(v) for v in camera['target'])).replace('FOV', str(camera['fov']))


